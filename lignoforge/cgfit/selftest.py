"""
Self-consistency test of the CG optimiser (minutes, no atomistic run).

A "reference" is generated by CG MD with *known* Lennard-Jones parameters on the
real bead graph of lignin chains; the optimiser then starts from perturbed
parameters (sigma +15 %, epsilon -40 %) and must recover the reference g(r),
pressure and parameters.  A failure here points at the CG tooling (mapping,
topology, sampling or update rule), not at the atomistic model.
"""

from __future__ import annotations

import pickle
import shutil
from pathlib import Path
from typing import Callable, Optional

import numpy as np

from lignoforge.cgfit import gmxio as G
from lignoforge.cgfit.model import CGParams
from lignoforge.cgfit.sampling import iter_frames, sample
from lignoforge.cgfit.workflow import CGParamJob, quick_config


def _random_start(sm, edge: float, rng) -> np.ndarray:
    pos: list = []

    def free(c):
        if not pos:
            return True
        d = np.array(pos) - c
        d -= edge * np.round(d / edge)
        return np.min(np.linalg.norm(d, axis=1)) > 0.32

    for s, e, _ in sm.mol_slices:
        while True:
            c = rng.uniform(0, edge, 3)
            if free(c):
                break
        chain = [c]
        pos.append(c)
        for _ in range(e - s - 1):
            for _try in range(500):
                v = rng.normal(size=3)
                c = chain[-1] + 0.4 * v / np.linalg.norm(v)
                if free(c % edge):
                    break
            chain.append(c)
            pos.append(c % edge)
    return np.array(pos) % edge


def run_selftest(workdir, iterations: int = 8, iter_ps: float = 1000.0, mixing: str = "free",
                 gmx: Optional[str] = None, log: Optional[Callable[[str], None]] = None) -> dict:
    wd = Path(workdir)
    shutil.rmtree(wd, ignore_errors=True)
    cfg = quick_config()
    cfg["ensemble"].update(n_distinct=2, copies=12)
    cfg["ensemble"]["spec"]["monomers"] = {"H": 0.0, "G": 0.5, "S": 0.5}
    cfg["cg"].update(cutoff=1.0, iterations=iterations, iter_ps=iter_ps, out_ps=2.0,
                     min_samples=20, mixing=mixing)
    job = CGParamJob(wd, cfg, gmx=gmx, log=log)
    job.run(["build"])
    sm, cg = job.system_map(), job.cfg["cg"]
    sig = {"SC": 0.45}                                     # per-type sigma, Lorentz-Berthelot cross terms
    true_nb = {p: {"sigma": 0.5 * sum(sig.get(t, 0.60) for t in p.split("-")), "epsilon": 2.5}
               for p in sm.pair_names}
    bonded = dict(default_bond={"r0": 0.4, "k": 4000.0}, default_angle={"theta0": 120.0, "k": 40.0})
    mk = lambda nb: CGParams(scheme="ring-side", temperature=500.0, cutoff=cg["cutoff"],   # noqa: E731
                             nonbonded=nb, **bonded)
    edge = G.box_edge_for_density(float(sm.bead_mass.sum()), 0.9)
    types = [sm.types[t] for t in sm.bead_type]
    truth = wd / "truth"
    truth.mkdir()
    G.write_text(truth / "start.gro", G.cg_gro_text(
        types, _random_start(sm, edge, np.random.default_rng(0)), [edge] * 3))
    job._cg_run(truth, mk(true_nb), truth / "start.gro", "nvt", 4 * iter_ps, 5)
    st = sample(sm, iter_frames(str(truth / "md.gro"), str(truth / "md.xtc"), begin_ps=iter_ps),
                mapped=True, rc=cg["cutoff"])
    p_ref = G.energy_average(job.gmx_cg, "md.edr", "Pressure", truth, iter_ps)
    (wd / "cg").mkdir(exist_ok=True)
    with open(wd / "cg" / "ref_stats.pkl", "wb") as fh:
        pickle.dump(st, fh)
    mk({p: {"sigma": q["sigma"] * 1.15, "epsilon": q["epsilon"] * 0.6}
        for p, q in true_nb.items()}).save(str(wd / "cg" / "params_000.json"))
    shutil.copy(truth / "md.gro", wd / "cg" / "start.gro")
    job._write("cg/reference_info.json", {"box_nm": [edge] * 3, "mean_edge_nm": edge})
    (wd / "reference").mkdir(exist_ok=True)
    job._write("reference/summary.json", {"pressure_bar": p_ref})
    job.run(["iterate"], force=True)

    hist = job._read("cg/history.json")
    final = CGParams.load(str(wd / "cg" / f"params_{len(hist):03d}.json"))
    return {
        "rmse_first": hist[0]["rdf_rmse"]["overall"], "rmse_last": hist[-1]["rdf_rmse"]["overall"],
        "pressure_ref": p_ref, "pressure_last": hist[-1]["pressure_bar"],
        "iterations": len(hist),
        "max_rel_sigma_error": max(abs(final.nonbonded[p]["sigma"] / true_nb[p]["sigma"] - 1)
                                   for p in true_nb),
        "history": hist,
    }
